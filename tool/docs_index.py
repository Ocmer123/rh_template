#!/usr/bin/env python3
"""Keeps the docs index in docs/README.md current. Standard library only (Python 3.7+).

  python tool/docs_index.py           rewrite the index
  python tool/docs_index.py --check   change nothing; exit 1 if the index is stale (CI)
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
README = DOCS / "README.md"
BEGIN = "<!-- BEGIN:index (generated by tool/docs_index.py, do not edit) -->"
END = "<!-- END:index -->"

# (heading, folder, filename pattern)
SECTIONS = [
    ("Architecture", "architecture", r"^(?!README).*\.md$"),
    ("Decisions (ADRs)", "decisions", r"^\d{4}-.*\.md$"),
    ("Implementation plans", "plans", r"^\d{4}-.*\.md$"),
]


def title_and_status(path):
    text = path.read_text(encoding="utf-8")
    title = path.stem
    for line in text.splitlines():
        if line.startswith("# "):
            title = line[2:].strip()
            break
    match = re.search(r"^Status:\s*(.+)$", text, re.MULTILINE)
    return title, (match.group(1).strip() if match else "-")


def build_index():
    out = []
    for heading, folder, pattern in SECTIONS:
        directory = DOCS / folder
        files = sorted(p for p in directory.glob("*.md") if re.match(pattern, p.name)) if directory.is_dir() else []
        out += ["## " + heading, ""]
        if not files:
            out += ["_None yet._", ""]
            continue
        out += ["| Document | Status |", "| --- | --- |"]
        for path in files:
            title, status = title_and_status(path)
            out.append("| [{}]({}/{}) | {} |".format(title, folder, path.name, status))
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    text = README.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        print("error: docs/README.md is missing the index markers", file=sys.stderr)
        return 1
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    updated = head + BEGIN + "\n\n" + build_index() + "\n" + END + tail

    if updated == text:
        print("docs index is up to date")
        return 0
    if args.check:
        print("::error::docs/README.md index is stale. Run: python tool/docs_index.py")
        return 1
    with open(str(README), "w", encoding="utf-8", newline="\n") as handle:
        handle.write(updated)
    print("docs index updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
